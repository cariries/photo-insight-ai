function detectLang() {
  try {
    const saved = localStorage.getItem("photo-insight.lang");
    if (saved && I18N[saved]) return saved;
  } catch {}
  return /^zh|^yue/i.test(navigator.language || "") ? "yue" : "en";
}

let LANG = detectLang();

function t(key, vars = {}) {
  const v = I18N[LANG][key] ?? I18N.en[key] ?? key;
  if (typeof v === "function") return v(vars);
  return v.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}

// data-i18n -> innerHTML (our own strings only), data-i18n-ph -> placeholder, data-i18n-title -> title
function applyI18n(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.innerHTML = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-ph]")) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
}

function setLang(lang) {
  LANG = I18N[lang] ? lang : "en";
  try { localStorage.setItem("photo-insight.lang", LANG); } catch {}
  document.documentElement.lang = LANG === "yue" ? "zh-Hant-HK" : "en";
  applyI18n();
}
